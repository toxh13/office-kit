/** 그 형식으로 만들 수 있는 서식 → [{ id, name, desc }] */
export function templatesFor(format) {
  return TEMPLATES.filter((t) => t.formats.includes(format)).map(({ id, name, desc }) => ({ id, name, desc }));
}

/** 서식 원고 (없거나 그 형식이 아니면 null) */
export function templateMarkdown(id, format) {
  const t = TEMPLATES.find((x) => x.id === id);
  return t && t.formats.includes(format) ? t.markdown : null;
}
